      and access.tenant_id = omehr_module_snapshots.tenant_id and access.active
      and (
        upper(access.role_code) in ('ADMIN','HR_DIRECTOR','IK_DIREKTORU','EXECUTIVE','CEO','GM','MANAGEMENT')
        or 'ALL' = any(access.region_scope) or 'ALL' = any(access.store_scope)
      )
  )
);

-- Satış hedefi okumasını da aynı kiracıdaki herkese açmak yerine mağaza
-- kapsamına veya şirket geneli role sınırla.
drop policy if exists "tenant members read sales targets" on public.omehr_sales_targets;
drop policy if exists "scoped users read sales targets" on public.omehr_sales_targets;
create policy "scoped users read sales targets" on public.omehr_sales_targets
for select to authenticated using (
  exists (
    select 1 from public.omehr_user_access access
    where access.auth_user_id = (select auth.uid())
      and access.tenant_id = omehr_sales_targets.tenant_id and access.active
      and (
        upper(access.role_code) in ('ADMIN','HR_DIRECTOR','IK_DIREKTORU','SATIS_DIREKTORU','SATIŞ_DİREKTÖRÜ','SALES_DIRECTOR','EXECUTIVE','CEO','GM','MANAGEMENT')
        or 'ALL' = any(access.region_scope) or 'ALL' = any(access.store_scope)
        or omehr_sales_targets.store_id = any(access.store_scope)
        or exists (
          select 1 from public.omehr_store_summary store
          where store.tenant_id = omehr_sales_targets.tenant_id
            and (store.store_id = omehr_sales_targets.store_id or store.store_name = omehr_sales_targets.store_name)
            and store.region_name = any(access.region_scope)
        )
      )
  )
);
